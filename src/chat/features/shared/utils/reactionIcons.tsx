// 4. Name → glyph map (verbatim from web v4/chat/utils/reactionIcons.ts) -------
export const REACTION_ICON_MAP: Record<
  string,
  ComponentType<ReactionGlyphProps>
> = {
  like: Like,
  love: Love,
  fire: Fire,
  happy: Happy,
  sad: Crying,
};

// Default message-reaction set + order (from amity-uikit-config.json
// `message_reactions`). Web derives this from CustomReactionProvider/config; RN
// has no runtime accessor for the top-level `message_reactions` key, so the
// picker falls back to this list (overridable via a prop).
export const DEFAULT_MESSAGE_REACTIONS = [
  'like',
  'love',
  'fire',
  'happy',
  'sad',
] as const;

// Renders the glyph for a reaction name, falling back to FallbackReaction — the
// RN equivalent of web's `REACTION_ICON_MAP[name] ?? FallbackReaction`.
export function ReactionGlyph({
  name,
  size,
}: ReactionGlyphProps & { name: string }) {
  const Glyph = REACTION_ICON_MAP[name] ?? FallbackReaction;
  return <Glyph size={size} />;
}
